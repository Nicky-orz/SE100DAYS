#include <stdio.h>
#include <stdbool.h>
#define maxn 105

const int dx[] = {-1,0,1,0};
const int dy[] = {0,1,0,-1};

int n, m;
int mp[maxn][maxn];

int main() {
    scanf("%d %d", &n, &m);
    for (int i = 1; i <= n; i++)
        for (int j = 1; j <= m; j++)
            scanf("%d", &mp[i][j]);
    for (int k = 0; k < 4; k++) {
        for (int i = 1; i <= n; i++)
            for (int j = 1; j <= m; j++) {
                if (mp[i][j] <= 0) continue;
                int nx = i + dx[k];
                int ny = j + dy[k];
                if (nx < 0 || ny < 0 || nx > n+1 || ny > m+1) continue;
                if (mp[nx][ny] > 0) continue;
                mp[i][j] += -mp[nx][ny];
                mp[nx][ny] = 0;
            }
        /*
        for (int i = 0; i <= n+1; i++) {
            for (int j = 0; j <= m+1; j++) 
                printf("%d ", mp[i][j]);
            printf("\n");
        }
        printf("\n");
        */
    }
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= m; j++) 
            printf("%d ", mp[i][j]);
        printf("\n");
    }
        

    return 0;
}
