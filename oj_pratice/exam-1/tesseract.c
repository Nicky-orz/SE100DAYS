#include <stdio.h>
char s[20];
int x[20], y[20], z[20], w[20];

int same(int *a, int i, int j) {
    if (a[i] == a[j]) return 1;
    else return 0;
}

int main() {
    scanf("%s", s);
    for (int i = 0; i < 2; i++)
        for (int j = 0; j < 2; j++)
            for (int k = 0; k < 2; k++)
                for (int p = 0; p < 2; p++) {
                    int t = i*8 + j*4 + k*2 + p;
                    x[t] = i;
                    y[t] = j;
                    z[t] = k;
                    w[t] = p;
                }
        int full = 1;
        int maxnum = 0, ans = 0;
        for (int i = 0; i < 16; i++) {
            if (s[i] == '1') continue;
            full = 0;
            int num = 0;
            for (int j = 0; j < 16; j++) {
                if (i == j || s[j] == '0') continue;
                int new = same(x,i,j) + same(y,i,j) + same(z,i,j) + same(w,i,j);
                if (new == 3)
                    num++;
            }
            if (num > maxnum)
                maxnum = num, ans = i;
            //printf("%d %d\n", i, num);
        }
    if (full) printf("-1");
    else printf("%d", ans);
   
    return 0;
}
