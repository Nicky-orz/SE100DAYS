#include <stdio.h>
#include <string.h>
#include <stdlib.h>
#define maxm 2005
#define maxq 500005



int m, n, q;
char name[maxm][25];
int R[maxm][maxm];
int box[maxq];
int cnt;

int main() {
    scanf("%d %d %d", &m, &n, &q);
    for (int i = 1; i <= m; i++) {
        scanf("%s",name[i]);
    }
    for (int i = 1; i <= n; i++) {
        int a, b, c;
        scanf("%d + %d = %d", &a, &b, &c);
        if (a > b) {
            int t = a;
            a = b;
            b = t;
        }
        R[a][b] = c;
    }
    for (int i = 1; i <= q; i++) {
        char ord[10]={};
        scanf("%4s", ord);
        if (ord[0] == 'A') {
            int t;
            scanf("%d", &t);
            box[++cnt] = t;
        }
        else {
            int *newbox = malloc((cnt+5) * sizeof(int));
            int newcnt = 0;
            for (int j = 1; j < cnt; j++) {
                if (box[j] == -1) continue;
                newcnt++;
                int now = box[j];
                int nxt = box[j+1];
                newbox[newcnt] = now;
                if (now > nxt) {
                    int t = now;
                    now = nxt;
                    nxt = t;
                }
                if (R[now][nxt] != 0) {
                        newbox[newcnt] = R[now][nxt];
                        box[j+1] = -1;
                    }
            }
            if (cnt > 0 && box[cnt] != -1)
                newbox[++newcnt] = box[cnt];

            for (int j = 1; j <= newcnt; j++)
                box[j] = newbox[j];
            cnt = newcnt;
        }
    }
    if (cnt == 0)
        printf("EMPTY");
    for (int i = 1; i <= cnt; i++) 
        printf("%s\n", name[box[i]]);
    return 0;
}
