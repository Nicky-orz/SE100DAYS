#include<bits/stdc++.h>
using namespace std;
void solve(){
    int n;
    int power = 100;
    cin>>n;
    for(int i=0;i<n;i++){
        int lose,get;
        cin>>lose>>get;
        if(lose >= 50)
            lose = 50;
        power = power - lose;
        if(power <= 100)
            power = 100;
        if(power >= 400)
            power = 400;
        power = power +get;
        if(power <= 100)
            power = 100;
        if(power >= 400)
            power = 400;
    }
    cout<<power<<endl;
}
int main(){
    int t;
    cin>>t;
    while(t--){
        solve();
    }
    return 0;
}
