#include<bits/stdc++.h>
using namespace std;
const int maxn = 200005;
typedef long long ll;

struct Node{
    int v,w;
};

int s[maxn],t[maxn];
ll ls[maxn];
ll lt[maxn];
ll ans = 0;
int par[maxn];
int n;

vector <Node> Edge[maxn];

void dfs(int root,int parent,int* arr,ll* larr){ //后序dfs
    par[root] = parent; //dfs同时确定父节点建树
    larr[root] = arr[root];
    for(auto edge : Edge[root]){
        if(edge.v == parent)
            continue;
        dfs(edge.v,root,arr,larr);
        larr[root] += larr[edge.v];
    }
}
int main(){
    cin>>n;
    for(int i=1;i<=n;i++)
        cin>>s[i];
    for(int i=1;i<=n;i++)
        cin>>t[i];
    for(int i=1;i<n;i++){
        int u,v,w;
        cin>>u>>v>>w;
        Node fro,pre;
        fro.v = v;fro.w = w;
        pre.v = u;pre.w = w;
        Edge[u].push_back(fro);
        Edge[v].push_back(pre);//不确定父节点，所以要双向图
    }
    
    dfs(1,0,s,ls);
    dfs(1,0,t,lt);

    for(int i=1;i<=n;i++){
        for(auto edge:Edge[i]){
            if(edge.v == par[i]) continue; //去掉子节点指向父节点的边，每条边只算子节点
            ll diff = abs(ls[edge.v] - lt[edge.v]);
            ans += (diff + edge.w - 1) / edge.w;
        }
    }
    cout<<ans;
    return 0;
}
